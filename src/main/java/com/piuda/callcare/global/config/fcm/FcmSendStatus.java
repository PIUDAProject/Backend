package com.piuda.callcare.global.config.fcm;

/**
 * FCM 발송 시도의 결과 상태.
 * <p>
 * 호출자(트리거)가 <b>재시도할지·다른 채널로 폴백할지</b>를 판단하는 기준이다.
 * 건수(success/failure)만으로는 "보낼 기기가 없었다"와 "보냈는데 전부 실패했다"가 구분되지 않아
 * 알림 유실이 조용히 지나간다 — 그래서 상태를 별도 값으로 표현한다.
 */
public enum FcmSendStatus {

    // 최소 1대 이상의 기기에 전달 성공. 일부 기기가 실패했어도 SENT다(기기 단위 실패는 failureCount로 확인).
    SENT,

    // 활성 토큰이 0개 — 앱 미설치이거나 토큰을 등록한 적이 없다. 재시도해도 결과가 같으므로 SMS 등 다른 채널이 필요하다.
    NO_TOKEN,

    // 서비스 계정 키 미설정 — 발송을 시도조차 하지 않았다. 오류가 아니라 기능 비활성 상태이며 이력도 남기지 않는다.
    NOT_CONFIGURED,

    // 발송을 시도했으나 전 건 실패 — FCM 일시 장애·인증 오류 등. 재시도 또는 폴백 대상이다.
    SEND_FAILED
}